"""Polymarket fee maths.

Two curves are implemented and both are selectable from config, because the
venue has used both and picking the wrong one silently changes every backtest
result:

``documented`` (default)
    Polymarket's published fee formula::

        fee_usdc = shares * feeRateBps/10_000 * p * (1 - p)

    where ``p`` is the execution price in probability space and
    ``feeRateBps = 700`` for crypto Up/Down markets (the "0.07" coefficient).
    The fee peaks at ``p = 0.5`` and vanishes at the extremes, which is the
    signature of this curve: a 50c contract is the most expensive to trade.

``symmetric``
    The simplified form quoted in most third-party write-ups::

        fee_usdc = shares * 0.07 * p * (1 - p)

    Identical to ``documented`` at 700 bps; kept as a separate name so a config
    that wants the plain textbook expression says so explicitly.

Fee pool vs. what you pay
-------------------------
``fee_usdc`` is the **total fee generated by the trade** (both sides). On
Polymarket the taker pays the pool and makers are rebated out of it. Therefore:

* :func:`taker_fee_usdc` -> full amount, charged to the aggressor;
* :func:`maker_fee_usdc` -> negative of the rebate share (a credit);
* :func:`net_fee_usdc` -> what the modelled order actually pays, by role.

All amounts are in USDC (quote units). ``p`` must be in (0, 1).
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Iterable, Literal, Sequence

CURVE_DOCUMENTED = "documented"
CURVE_SYMMETRIC = "symmetric"
FeeCurve = Literal["documented", "symmetric"]

#: 700 bps == the 0.07 coefficient in the published formula.
DEFAULT_FEE_RATE_BPS = 700.0
DEFAULT_COEFFICIENT = DEFAULT_FEE_RATE_BPS / 10_000.0  # 0.07
DEFAULT_MAKER_REBATE_SHARE = 0.25


class FeeError(ValueError):
    """Raised for impossible fee inputs (bad price, negative shares)."""


def _check_price(price: float, *, allow_extremes: bool = False) -> float:
    p = float(price)
    if allow_extremes:
        if not 0.0 <= p <= 1.0:
            raise FeeError(f"price must be within [0, 1], got {price!r}")
    elif not 0.0 < p < 1.0:
        raise FeeError(
            f"price must be strictly inside (0, 1) for the fee curve, got {price!r}"
        )
    return p


def _check_shares(shares: float) -> float:
    value = float(shares)
    if value < 0:
        raise FeeError(f"shares must be >= 0, got {shares!r}")
    return value


def fee_pool_usdc(
    shares: float,
    price: float,
    *,
    coefficient: float = DEFAULT_COEFFICIENT,
    curve: FeeCurve = CURVE_DOCUMENTED,
) -> float:
    """Total fee generated by a trade: ``shares * coefficient * p * (1 - p)``.

    This is the number the venue's formula produces. Whether *you* pay all of it
    depends on your role - use :func:`net_fee_usdc` for that.
    """
    c = _check_shares(shares)
    p = _check_price(price)
    if curve == CURVE_DOCUMENTED:
        if coefficient < 0:
            raise FeeError("coefficient must be >= 0")
        return c * coefficient * p * (1.0 - p)
    if curve == CURVE_SYMMETRIC:
        return c * DEFAULT_COEFFICIENT * p * (1.0 - p)
    raise FeeError(f"unknown fee curve: {curve!r}")


def taker_fee_usdc(
    shares: float,
    price: float,
    *,
    coefficient: float = DEFAULT_COEFFICIENT,
    curve: FeeCurve = CURVE_DOCUMENTED,
) -> float:
    """Fee charged to the aggressor: the full pool."""
    return fee_pool_usdc(shares, price, coefficient=coefficient, curve=curve)


def maker_fee_usdc(
    shares: float,
    price: float,
    *,
    coefficient: float = DEFAULT_COEFFICIENT,
    curve: FeeCurve = CURVE_DOCUMENTED,
    rebate_share: float = DEFAULT_MAKER_REBATE_SHARE,
) -> float:
    """Maker side, expressed as a signed amount: negative == you receive USDC."""
    if not 0.0 <= rebate_share <= 1.0:
        raise FeeError("rebate_share must be in [0, 1]")
    pool = fee_pool_usdc(shares, price, coefficient=coefficient, curve=curve)
    return -pool * rebate_share


def net_fee_usdc(
    shares: float,
    price: float,
    *,
    is_taker: bool = True,
    coefficient: float = DEFAULT_COEFFICIENT,
    curve: FeeCurve = CURVE_DOCUMENTED,
    rebate_share: float = DEFAULT_MAKER_REBATE_SHARE,
) -> float:
    """Signed fee actually paid by the order: positive = cost, negative = rebate."""
    if is_taker:
        return taker_fee_usdc(shares, price, coefficient=coefficient, curve=curve)
    return maker_fee_usdc(
        shares,
        price,
        coefficient=coefficient,
        curve=curve,
        rebate_share=rebate_share,
    )


def fee_as_price(fee_usdc: float, shares: float) -> float:
    """Express a fee as a per-share price offset (USDC per share)."""
    c = _check_shares(shares)
    if c == 0:
        return 0.0
    return float(fee_usdc) / c


def fee_bps_of_notional(fee_usdc: float, shares: float, price: float) -> float:
    """Fee expressed in basis points of traded notional (for cost comparison)."""
    notional = _check_shares(shares) * _check_price(price)
    if notional == 0:
        return 0.0
    return float(fee_usdc) / notional * 10_000.0


def shares_for_notional(notional: float, price: float) -> float:
    """How many shares a USDC notional buys at ``price`` (excluding fees)."""
    p = _check_price(price)
    if notional < 0:
        raise FeeError("notional must be >= 0")
    return float(notional) / p


def notional_for_shares(shares: float, price: float) -> float:
    return _check_shares(shares) * _check_price(price)


def break_even_move(price: float, *, coefficient: float = DEFAULT_COEFFICIENT) -> float:
    """Probability move needed to cover the taker fee alone.

    Solving ``move * shares = shares * coefficient * p * (1 - p)`` gives
    ``move = coefficient * p * (1 - p)`` - the round-trip cost floor a sniper
    must clear before any strategy edge is real.
    """
    p = _check_price(price)
    return coefficient * p * (1.0 - p)


def max_fee_price() -> float:
    """The price at which the fee curve peaks (0.5)."""
    return 0.5


@dataclass(frozen=True)
class FeeBreakdown:
    """Itemised cost of one simulated fill."""

    shares: float
    price: float
    role: str
    pool_usdc: float
    charged_usdc: float
    coefficient: float = DEFAULT_COEFFICIENT
    curve: str = CURVE_DOCUMENTED

    @property
    def notional_usdc(self) -> float:
        return self.shares * self.price

    @property
    def cost_bps(self) -> float:
        return fee_bps_of_notional(self.charged_usdc, self.shares, self.price)

    @property
    def is_rebate(self) -> bool:
        return self.charged_usdc < 0

    def as_dict(self) -> dict:
        return {
            "shares": round(self.shares, 8),
            "price": round(self.price, 6),
            "role": self.role,
            "notional_usdc": round(self.notional_usdc, 6),
            "pool_usdc": round(self.pool_usdc, 8),
            "charged_usdc": round(self.charged_usdc, 8),
            "cost_bps": round(self.cost_bps, 4),
            "curve": self.curve,
        }


def fee_breakdown(
    shares: float,
    price: float,
    *,
    is_taker: bool = True,
    coefficient: float = DEFAULT_COEFFICIENT,
    curve: FeeCurve = CURVE_DOCUMENTED,
    rebate_share: float = DEFAULT_MAKER_REBATE_SHARE,
) -> FeeBreakdown:
    """Full itemisation, for logging and trade records."""
    pool = fee_pool_usdc(shares, price, coefficient=coefficient, curve=curve)
    charged = net_fee_usdc(
        shares,
        price,
        is_taker=is_taker,
        coefficient=coefficient,
        curve=curve,
        rebate_share=rebate_share,
    )
    return FeeBreakdown(
        shares=float(shares),
        price=float(price),
        role="taker" if is_taker else "maker",
        pool_usdc=pool,
        charged_usdc=charged,
        coefficient=coefficient,
        curve=curve,
    )


def total_fees(breakdowns: Iterable[FeeBreakdown]) -> float:
    return float(sum(item.charged_usdc for item in breakdowns))


def fee_curve_table(
    prices: Sequence[float] | None = None,
    *,
    shares: float = 100.0,
    coefficient: float = DEFAULT_COEFFICIENT,
) -> list[dict]:
    """Tabulate the fee curve - handy for sanity checks and reports."""
    grid = prices if prices is not None else [0.05, 0.10, 0.25, 0.50, 0.75, 0.90, 0.95]
    rows = []
    for price in grid:
        p = _check_price(price)
        rows.append(
            {
                "price": p,
                "shares": shares,
                "notional_usdc": round(shares * p, 6),
                "taker_fee_usdc": round(taker_fee_usdc(shares, p, coefficient=coefficient), 6),
                "fee_bps_of_notional": round(
                    fee_bps_of_notional(
                        taker_fee_usdc(shares, p, coefficient=coefficient), shares, p
                    ),
                    2,
                ),
                "break_even_move": round(break_even_move(p, coefficient=coefficient), 6),
            }
        )
    return rows
